MAXIMUM_BYTES = 20 * 1024**3


def metadata_sha(path):
    require(
        path.is_file()
        and not path.is_symlink()
        and path.stat().st_size <= 128 * 1024**2,
        "input preparation metadata size or link is invalid",
    )
    return hashlib.sha256(path.read_bytes()).hexdigest()


def paired_inventory(rows, count):
    require(
        type(count) is int and 1 <= count <= 500000 and len(rows) == count,
        "original pair hash inventory has a missing or extra row",
    )
    result = {}
    for identity, row in enumerate(rows):
        require(
            isinstance(row, dict)
            and set(row) in ({"path", "sha256"}, {"pair", "sha256"}),
            "original pair hash row schema differs",
        )
        name = f"{identity//256:06d}/{identity:09d}.json"
        if "path" in row:
            require(
                row["path"] == name,
                "original pair paths are duplicated or out of order",
            )
        else:
            require(
                type(row["pair"]) is int and row["pair"] == identity,
                "original pair identities are duplicated or out of order",
            )
        result[name] = digest_text(row["sha256"])
    return result


def data_catalog(
    project, corpus, dataset, prefix, output, commit, guard, *, diagnostic=False
):
    """Create external selected-view manifests without writing into originals."""
    project, corpus, dataset, output = (
        Path(p).resolve() for p in [project, corpus, dataset, output]
    )
    output.mkdir(parents=True, exist_ok=False)
    roots = {"corpus": corpus, "dataset": dataset, "config": project / "config"}
    if not diagnostic:
        roots["prefix"] = Path(prefix).resolve()
    files = {}
    with contextlib.ExitStack() as stack:
        views = {
            key: stack.enter_context(Bundle(root, 3600)) for key, root in roots.items()
        }
        manifest = views["dataset"].json("DATASET.json")
        data_sha = views["dataset"].sha("DATASET.json", 4 * 1024**2, check=guard)
        require(
            diagnostic or data_sha == FULL_DATASET,
            "original full dataset identity differs",
        )
        pairs = len(views["dataset"].json("SOURCE_PAIRS.json", 128 * 1024**2))
        require(
            (diagnostic and 1 <= pairs <= 100) or (not diagnostic and pairs == 114791),
            "preparation pair count does not match its explicit profile",
        )

        def add(role, name, destination, expected=None, maximum=4 * 1024**2):
            guard()
            value = views[role].sha(name, maximum, check=guard)
            require(
                expected is None or value == expected,
                "original preparation input changed: " + name,
            )
            files[destination] = {"shard": role, "path": name, "sha256": value}

        for name in sorted(DATASET_FILES):
            expected = (
                data_sha
                if name == "DATASET.json"
                else (
                    manifest["source_pairs_sha256"]
                    if name == "SOURCE_PAIRS.json"
                    else manifest["files"].get(name)
                )
            )
            add(
                "dataset",
                name,
                "dataset/" + name,
                expected,
                128 * 1024**2 if name == "SOURCE_PAIRS.json" else 8 * 1024**3,
            )
        require(
            views["corpus"].json("CONFIG.json") == manifest["corpus_config"],
            "original corpus configuration disagrees with the dataset",
        )
        add("corpus", "CONFIG.json", "corpus/CONFIG.json")
        for name in ["studies.json", "strength-openings.json"]:
            add(
                "config",
                name,
                "config/" + name,
                manifest["heldout_inputs"]["config/" + name],
            )
        if diagnostic:
            add("corpus", "SUMMARY.json", "corpus/SUMMARY.json")
            rows = views["dataset"].json("SOURCE_PAIRS.json", 128 * 1024**2)
        else:
            for name in ["INTERRUPTED.json", "SESSIONS.jsonl"]:
                add("corpus", name, "corpus/" + name)
            add("prefix", "PROTOCOL.json", "prefix/PROTOCOL.json", FULL_PREFIX)
            add(
                "prefix",
                "PAIR_HASHES.jsonl",
                "prefix/PAIR_HASHES.jsonl",
                FULL_PAIRS,
                128 * 1024**2,
            )
            rows = [
                strict_json(line)
                for line in views["prefix"]
                .bytes("PAIR_HASHES.jsonl", 128 * 1024**2)
                .splitlines()
            ]
        for name, value in paired_inventory(rows, pairs).items():
            files["corpus/" + name] = {"shard": "corpus", "path": name, "sha256": value}
    descriptors = {}
    for key, root in roots.items():
        guard()
        path = output / (key + "-view.json")
        atomic(
            path,
            {
                "schema": "caissa-input-view-v1",
                "files": {
                    ref["path"]: ref["sha256"]
                    for ref in files.values()
                    if ref["shard"] == key
                },
            },
        )
        descriptors[key] = {
            "root": str(root.relative_to(project)),
            "manifest": str(path.relative_to(project)),
            "manifest_sha256": metadata_sha(path),
        }
    rule = {
        "schema": "caissa-original-data-catalog-v1",
        "status": "frozen",
        "profile": "diagnostic" if diagnostic else "full",
        "source_commit": commit,
        "dataset_sha256": data_sha,
        "pairs": pairs,
        "output": (
            str((output / "diagnostic-replay").relative_to(project))
            if diagnostic
            else AUDIT_OUTPUT + "/data"
        ),
        "resources": {
            "maximum_wall_seconds": 120 if diagnostic else 21600,
            "maximum_active_seconds": 120 if diagnostic else 21600,
            "maximum_staging_seconds": 30 if diagnostic else 3600,
            "maximum_input_gib": 1 if diagnostic else 20,
            "maximum_additional_gib": 1 if diagnostic else 20,
            "minimum_free_gib": 1 if diagnostic else 10,
            "maximum_attempts": 1,
            "parent_deadline_unix": None if diagnostic else PARENT_DEADLINE,
        },
        "shards": descriptors,
        "files": files,
    }
    path = output / "CATALOG.json"
    atomic(path, rule)
    data_contract(path, metadata_sha(path), commit, diagnostic)
    return path


class LearningPack:
    """Only verified streaming copies populate the new learning input bundle."""

    def __init__(self, roots, output, guard):
        self.output = Path(output).resolve()
        roots = {key: Path(root).resolve() for key, root in roots.items()}
        require(
            1 <= len(roots) <= 8 and len(set(roots.values())) == len(roots),
            "learning input roots are missing or aliased",
        )
        require(
            all(
                not self.output.is_relative_to(root)
                and not root.is_relative_to(self.output)
                for root in roots.values()
            ),
            "learning preparation must preserve original directories",
        )
        self.output.mkdir(parents=True, exist_ok=False)
        self.stack = contextlib.ExitStack()
        self.views = {
            key: self.stack.enter_context(Bundle(root, 3600))
            for key, root in roots.items()
        }
        for view in self.views.values():
            view.identities = {}
        self.guard, self.references, self.allocated = guard, {}, 0

    def add(self, role, name, destination, expected=None, maximum=128 * 1024**2):
        from verification.source import relative_path

        relative_path(destination)
        require(
            destination not in self.references and len(self.references) < 1000,
            "learning preparation has a duplicate or excessive artifact inventory",
        )
        require(
            type(maximum) is int and 0 < maximum <= 4 * 1024**3,
            "learning preparation artifact byte ceiling is invalid",
        )
        view = self.views[role]
        digest = view.sha(name, maximum, check=self.guard)
        require(
            expected is None or digest == expected,
            "original learning bytes changed: " + name,
        )
        view.identities[name] = digest
        stream, info = view.open(name)
        stream.close()
        require(
            self.allocated + info.st_size <= MAXIMUM_BYTES,
            "learning preparation combined byte ceiling exhausted",
        )
        target = self.output / destination
        target.parent.mkdir(parents=True, exist_ok=True)
        copied = view.copy(name, target, maximum, check=self.guard)
        self.allocated += copied["bytes"]
        result = {"path": destination, "sha256": digest}
        self.references[destination] = result
        return result

    def finish(self, inputs):
        atomic(self.output / "LEARNING_INPUTS.json", inputs)
        files = {name: ref["sha256"] for name, ref in self.references.items()}
        files["LEARNING_INPUTS.json"] = metadata_sha(
            self.output / "LEARNING_INPUTS.json"
        )
        atomic(self.output / "MANIFEST.json", {"files": files})
        return {
            "root": str(self.output),
            "manifest_sha256": metadata_sha(self.output / "MANIFEST.json"),
            "inputs_sha256": files["LEARNING_INPUTS.json"],
            "copied_bytes": self.allocated,
        }

    def close(self):
        self.stack.close()


def learning_catalog(project, output, guard):
    project, output = Path(project).resolve(), Path(output).resolve()
    roots = {
        "model": project / "runs/searched-full-model-v3",
        "dataset": project / "data/searched-full-v3-prepared",
        "config": project / "config",
        "wire": project / "results/precision-v4-2026-10-25",
    }
    pack = LearningPack(roots, output, guard)
    try:
        add = pack.add
        metadata = add("dataset", "DATASET.json", "dataset/DATASET.json", FULL_DATASET)
        dataset = pack.views["dataset"].json("DATASET.json")
        protocol = add("config", "protocol-v4.json", "protocol.json")
        original = add(
            "config", "protocol-v3.json", "original/PROTOCOL.json", ORIGINAL_PROTOCOL
        )
        model = add(
            "model",
            "MODEL_CAMPAIGN.json",
            "original/MODEL_CAMPAIGN.json",
            ORIGINAL_MODEL,
        )
        selection = add(
            "model",
            "selection/SELECTION.json",
            "selection/SELECTION.json",
            ORIGINAL_SELECTION,
        )
        checkpoint = add(
            "model", "selection/selected.pt", "selection/selected.pt", CHECKPOINT
        )
        network = add(
            "model", "selection/selected.cai", "original/selected.cai", ORIGINAL_NETWORK
        )
        deployed = add("wire", "selected-v4.cai", "deployment/selected.cai", DEPLOYED)
        arrays = {
            name: add(
                "dataset", name, "dataset/" + name, dataset["files"][name], 4 * 1024**3
            )
            for name in [
                "train-features.npy",
                "validation-features.npy",
                "validation-targets.npy",
            ]
        }
        baseline_receipt = add(
            "model", "baselines/BASELINES.json", "baseline/BASELINES.json"
        )
        baseline_meta = pack.views["model"].json("baselines/BASELINES.json")
        model_meta = pack.views["model"].json("MODEL_CAMPAIGN.json")
        baseline = {
            "BASELINES.json": baseline_receipt,
            **{
                name: add(
                    "model",
                    "baselines/" + name,
                    "baseline/" + name,
                    (
                        model_meta["engine_sha256"]
                        if name == "caissa"
                        else baseline_meta["files"].get(name)
                    ),
                    4 * 1024**3 if name.endswith(".npy") else 128 * 1024**2,
                )
                for name in [
                    "caissa",
                    "train-baseline.npy",
                    "validation-baseline.npy",
                ]
            },
        }
        seeds, raw = {}, {}
        for seed in [17, 41, 73]:
            prefix = "seed" + str(seed) + "/"
            seeds[str(seed)] = {
                "config": add("model", prefix + "CONFIG.json", prefix + "CONFIG.json"),
                "checkpoints": add(
                    "model", prefix + "CHECKPOINTS.json", prefix + "CHECKPOINTS.json"
                ),
            }
            initial_identity = add(
                "model", prefix + "INITIAL.json", prefix + "INITIAL.json"
            )
            initial = pack.views["model"].json(prefix + "INITIAL.json")
            raw[str(seed)] = {
                "initial": add(
                    "model",
                    prefix + "initial.pt",
                    prefix + "initial.pt",
                    initial["sha256"],
                ),
                "initial_identity": initial_identity,
                "observations": add(
                    "model",
                    prefix + "observations.jsonl",
                    prefix + "observations.jsonl",
                ),
                "summary": add(
                    "model", prefix + "SUMMARY.json", prefix + "SUMMARY.json"
                ),
                "checkpoints": {},
            }
            pointers = pack.views["model"].json(prefix + "CHECKPOINTS.json")
            for step in range(250, 20001, 250):
                name = f"checkpoints/step-{step:08d}.pt"
                expected = next(
                    (
                        ref["sha256"]
                        for ref in pointers.values()
                        if isinstance(ref, dict) and ref.get("path") == name
                    ),
                    None,
                )
                raw[str(seed)]["checkpoints"][str(step)] = add(
                    "model", prefix + name, prefix + name, expected
                )
        inputs = {
            "schema": "caissa-original-learning-inputs-v1",
            "protocol": protocol,
            "dataset": {"metadata": metadata},
            "network": {
                "artifact": deployed,
                "checkpoint_sha256": CHECKPOINT,
                "classical_contract": 1,
                "neural_weight": 10,
            },
            "learning": {"selection": selection, "seeds": seeds},
            "domains": {
                "G07": {
                    "driver": "original-learning-component-v1",
                    "artifacts": list(pack.references.values()),
                    "original_learning": {
                        "protocol": original,
                        "model_campaign": model,
                        "network": network,
                        "checkpoint": checkpoint,
                        "dataset": arrays,
                        "baseline": baseline,
                        "seeds": raw,
                    },
                }
            },
        }
        result = pack.finish(inputs)
        # Validate the complete inventory against the existing independent
        # lineage reader, without loading tensors, selecting models or training.
        with Bundle(output, 3600) as bundle:
            bundle.identities = {
                name: ref["sha256"] for name, ref in pack.references.items()
            }
            bundle.identities["LEARNING_INPUTS.json"] = result["inputs_sha256"]
            args, rule, model, _ = admit_lineage(bundle, inputs)
            inventory(bundle, inputs, args, rule, model)
        return result
    finally:
        pack.close()


def prepare(checkout, commit):
    checkout = Path(checkout).resolve()
    output = checkout / OUTPUT
    require(not output.exists(), "G07 input preparation scope already exists; no reset")
    require(
        strength_settled(checkout),
        "frozen strength pipeline is not settled; defer input preparation",
    )
    require(
        time.time() + 3600 + RESOURCES["maximum_wall_seconds"] <= PARENT_DEADLINE,
        "input preparation and audit cannot fit the original parent deadline",
    )
    lease = HostLease(checkout / "runs")
    scope = power = None
    closed = False
    try:
        source = {
            "schema": "caissa-source-inputs-v2",
            "policy": PRODUCT,
            "commit": commit,
            "files": snapshot(checkout, commit, PRODUCT),
        }
        verify_checkout(checkout, source, commit, PRODUCT)
        require(
            Path(__file__).resolve().parents[1] == checkout,
            "launch preparation from its trusted checkout",
        )
        scope = RecoveryScope(
            output,
            {
                "source_commit": commit,
                "dataset_sha256": FULL_DATASET,
                "checkpoint_sha256": CHECKPOINT,
            },
            3600,
            output / "empty-input-accounting",
            10,
            20,
            maximum_authorized_seconds=21600,
            maximum_active_seconds=3600,
        )
        power = PowerGuard(POLICY if sys.platform == "darwin" else None)
        power.start(output)
        host = HostGuard(output, scope, power)

        def guard():
            lease.check()
            host.check()

        guard()
        atomic(output / "SOURCE_INPUTS.json", source)
        archive_source(checkout, output / "source", commit, source["files"])
        catalog = data_catalog(
            checkout,
            checkout / "data/searched-full-v3",
            checkout / "data/searched-full-v3-prepared",
            checkout / "runs/searched-full-v3-finalization-v2/inputs",
            output / "data-catalog",
            commit,
            guard,
        )
        learning = learning_catalog(checkout, output / "learning", guard)
        plan = {
            "schema": "caissa-g07-live-audit-v1",
            "status": "frozen",
            "source_commit": commit,
            "output": AUDIT_OUTPUT,
            "dataset_sha256": FULL_DATASET,
            "checkpoint_sha256": CHECKPOINT,
            "deployed_network_sha256": DEPLOYED,
            "resources": RESOURCES,
            "data": {
                "catalog": str(catalog.relative_to(checkout)),
                "sha256": metadata_sha(catalog),
            },
            "learning": {
                key: str(Path(value).relative_to(checkout)) if key == "root" else value
                for key, value in learning.items()
                if key in {"root", "manifest_sha256", "inputs_sha256"}
            },
        }
        path = output / "PLAN.json"
        atomic(path, plan)
        from verification.g07_audit import contract

        contract(path, metadata_sha(path), commit)
        guard()
        result = {
            "schema": "caissa-original-g07-input-preparation-v1",
            "status": "prepared",
            "source_commit": commit,
            "plan_sha256": metadata_sha(path),
            "data_catalog_sha256": plan["data"]["sha256"],
            "learning": learning,
            "completed_unix": time.time(),
            "deadline_unix": scope.deadline,
            "originals_unchanged": True,
            "full_G07_certified": False,
            "full_acceptance": False,
            "scope_closed": True,
        }
        scope.close()
        closed = True
        atomic(output / "PREPARATION.json", result)
        return result
    except BaseException as error:
        if scope is not None:
            atomic(
                output / "FAILED.json",
                {
                    "type": type(error).__name__,
                    "reason": str(error),
                    "unix": time.time(),
                    "full_acceptance": False,
                },
            )
        raise
    finally:
        try:
            if power is not None:
                power.close()
        finally:
            if scope is not None and not closed:
                scope.close()
            lease.close()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--checkout", type=Path, required=True)
    parser.add_argument("--expected-commit", required=True)
    parser.add_argument("--run-audit", action="store_true")
    args = parser.parse_args()
    try:
        result = prepare(args.checkout, args.expected_commit)
        print(json.dumps(result), flush=True)
        if args.run_audit:
            output = args.checkout.resolve() / OUTPUT
            launcher = "import runpy,sys;sys.path.insert(0,sys.argv.pop(1));runpy.run_module('verification.g07_audit',run_name='__main__')"
            os.execv(
                sys.executable,
                [
                    sys.executable,
                    "-P",
                    "-X",
                    "pycache_prefix=" + str(output / "audit-runtime-cache"),
                    "-c",
                    launcher,
                    str(output / "source"),
                    str(output / "PLAN.json"),
                    "--expected-plan-sha256",
                    result["plan_sha256"],
                    "--checkout",
                    str(args.checkout.resolve()),
                    "--expected-commit",
                    args.expected_commit,
                    "--archived-source",
                ],
            )
        return 0
    except (ValueError, KeyError, TypeError, OSError, RuntimeError) as error:
        print(
            json.dumps(
                {
                    "status": "rejected",
                    "reason": str(error),
                    "full_G07_certified": False,
                    "full_acceptance": False,
                }
            )
        )
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
